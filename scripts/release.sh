#!/usr/bin/env bash
# Cut a release: build a universal GH Hub.app, publish it as a GitHub release,
# and point the Homebrew tap's cask at it. Same shape as cpx's release.
#
#   scripts/release.sh <version> [--dry-run]
set -euo pipefail

VERSION="${1:-}"
DRY_RUN="${2:-}"
REPO="menico/gh-hub"
TAP_REPO="menico/homebrew-tap"
CASK="gh-hub"

if [[ -z "$VERSION" ]]; then
  echo "usage: scripts/release.sh <version> [--dry-run]   e.g. 0.2.0" >&2
  exit 1
fi
VERSION="${VERSION#v}"
TAG="v$VERSION"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
DIST="$ROOT/build/dist"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }

# The version lives in VERSION; the app's Info.plist is stamped from it.
if [[ "$(cat VERSION)" != "$VERSION" ]]; then
  echo "VERSION says $(cat VERSION) but you asked for $VERSION. Update VERSION first." >&2
  exit 1
fi

say "Testing"
swift test >/dev/null

say "Building GH Hub.app as a universal binary"
rm -rf "$DIST"; mkdir -p "$DIST"
APP="$(./build.sh "$VERSION" --universal)"
lipo -archs "$APP/Contents/MacOS/gh-hub"

say "Packing the dmg"
STAGE="$(mktemp -d)"
cp -R "$APP" "$STAGE/GH Hub.app"
ln -s /Applications "$STAGE/Applications"
DMG="$DIST/gh-hub-$VERSION-universal.dmg"
hdiutil create -quiet -volname "GH Hub" -srcfolder "$STAGE" -ov -format UDZO "$DMG"
rm -rf "$STAGE"

say "Checksum"
(cd "$DIST" && shasum -a 256 * | tee checksums.txt)
SHA_DMG="$(shasum -a 256 "$DMG" | cut -d' ' -f1)"

if [[ "$DRY_RUN" == "--dry-run" ]]; then
  say "Dry run — built in $DIST, nothing published"
  exit 0
fi

if [[ -n "$(git status --porcelain)" ]]; then
  echo "Commit your changes first; the release is tagged from HEAD." >&2
  exit 1
fi

say "Publishing $TAG to $REPO"
git tag -f "$TAG"
git push origin HEAD "$TAG" --force
gh release view "$TAG" --repo "$REPO" >/dev/null 2>&1 \
  && gh release delete "$TAG" --repo "$REPO" --yes
gh release create "$TAG" --repo "$REPO" --title "$TAG" \
  --notes "Install: \`brew tap menico/tap && brew install --cask $CASK\`" \
  "$DMG" "$DIST/checksums.txt"

say "Pointing the tap at $TAG"
TAP="$(mktemp -d)"
gh repo clone "$TAP_REPO" "$TAP" -- --quiet
mkdir -p "$TAP/Casks"

cat > "$TAP/Casks/$CASK.rb" <<CASKFILE
# Generated by scripts/release.sh in $REPO — edit that, not this.
cask "$CASK" do
  version "$VERSION"
  sha256 "$SHA_DMG"

  url "https://github.com/$REPO/releases/download/v#{version}/gh-hub-#{version}-universal.dmg"
  name "GH Hub"
  desc "Review, approve and run GitHub pull requests, issues and Actions across gh accounts"
  homepage "https://github.com/$REPO"

  depends_on macos: :sonoma
  depends_on formula: "gh"

  app "GH Hub.app"

  # The app is ad-hoc signed rather than notarised, so macOS quarantines it
  # on download. Removing the flag here saves a right-click-open.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/GH Hub.app"]
  end

  # GH Hub keeps no credentials (it borrows gh's); only its preferences.
  zap trash: [
    "~/Library/Preferences/io.github.menico.gh-hub.plist",
    "~/Library/Application Support/io.github.menico.gh-hub",
  ]
end
CASKFILE

git -C "$TAP" add -A
git -C "$TAP" commit -q -m "$CASK $VERSION" || { echo "tap already up to date"; }
git -C "$TAP" push -q
rm -rf "$TAP"

say "Released $TAG"
echo
echo "  brew tap menico/tap"
echo "  brew trust menico/tap"
echo "  brew install --cask $CASK"
echo
echo "To update later:  brew update && brew upgrade --cask $CASK"
